#!/usr/bin/env python3
"""Generate shell/src/splash_data.h: the boot logo and a small ASCII font as
8-bit alpha bitmaps, so vortex-splash needs no image or font loading.

    tools/gen-splash-data.py   (needs Pillow; run after changing the logo)
"""
import os

from PIL import Image, ImageDraw, ImageFont

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGO = os.path.join(TOP, "assets/boot/vortex-logo.png")
FONT = os.path.join(TOP, "assets/fonts/Roboto-Regular.ttf")
OUT = os.path.join(TOP, "shell/src/splash_data.h")
SIZE = 12


def carray(data, per_line=24):
    rows = []
    for i in range(0, len(data), per_line):
        rows.append("    " + ",".join(str(b) for b in data[i : i + per_line]) + ",")
    return "\n".join(rows)


def main():
    logo = Image.open(LOGO).convert("L")
    font = ImageFont.truetype(FONT, SIZE)
    ascent, descent = font.getmetrics()
    height = ascent + descent

    glyphs, bitmap = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        adv = round(font.getlength(ch))
        w = max(adv, 1)
        im = Image.new("L", (w, height), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
        glyphs.append((len(bitmap), w, adv))
        bitmap += im.tobytes()

    with open(OUT, "w") as f:
        f.write("/* Generated by tools/gen-splash-data.py: do not edit. */\n")
        f.write("#define SPLASH_LOGO_W %d\n#define SPLASH_LOGO_H %d\n" % logo.size)
        f.write("static const unsigned char splash_logo[] = {\n%s\n};\n" % carray(logo.tobytes()))
        f.write("#define SPLASH_FONT_H %d\n" % height)
        f.write("/* ASCII 32..126: offset into splash_font_px, bitmap width, advance */\n")
        f.write("static const struct { unsigned short off; unsigned char w, adv; } splash_glyphs[] = {\n")
        for off, w, adv in glyphs:
            f.write("    { %d, %d, %d },\n" % (off, w, adv))
        f.write("};\n")
        f.write("static const unsigned char splash_font_px[] = {\n%s\n};\n" % carray(bitmap))


if __name__ == "__main__":
    main()
